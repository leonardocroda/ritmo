"""Engine e sessão SQLAlchemy.

Postgres desde a v1 (AD-007), driver psycopg3 — caminho único, sem código
específico de dialeto. Config 100% via DATABASE_URL (requisito travado).
"""

from collections.abc import Iterator
from datetime import date
import json

from sqlalchemy import create_engine, text
from sqlalchemy.orm import Session, sessionmaker

from app.core.config import get_settings
from app.db.base import Base
from app.profile.calc import DEFAULT_BOUNDS

settings = get_settings()

# Neon (produção, docs-site/docs/infra/deploy.md): a compute hiberna após 5 min sem queries
# e encerra as conexões idle do pool — pre_ping recicla a conexão morta no
# checkout em vez de estourar OperationalError na request (transparência
# do scale-to-zero). Knobs do DRIVER, não de dialeto: o caminho continua
# único (AD-007) e inofensivos no Postgres local do compose.
engine = create_engine(
    settings.database_url,
    pool_pre_ping=True,
    # A string pooled (-pooler) atravessa o PgBouncer do Neon em modo
    # transaction: o prepare automático do psycopg3 (liga após 5 execuções
    # da mesma query) quebra entre transações ("prepared statement already
    # exists"). None desliga o prepare no cliente.
    connect_args={"prepare_threshold": None},
)

SessionLocal = sessionmaker(bind=engine, autoflush=False, expire_on_commit=False)


def get_db() -> Iterator[Session]:
    """Dependência FastAPI: uma sessão por request."""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


def _migrate_users_columns() -> None:
    """Migração idempotente das colunas de auth em bases criadas ANTES da
    feature (emenda UAT, 20/10).

    O ``create_all`` só cria tabela AUSENTE — nunca altera tabela
    existente. Bancos de dev/produção anteriores à feature auth têm a
    ``users`` sem ``email``/``password_hash`` e crasham no startup
    (UndefinedColumn). Migração condicional à coluna: base nova
    (create_all já criou tudo, inclusive a unique) não ganha índice
    redundante.
    """
    with engine.begin() as conn:
        columns = {
            row[0]
            for row in conn.execute(
                text(
                    "SELECT column_name FROM information_schema.columns "
                    "WHERE table_name = 'users'"
                )
            )
        }
        if "email" in columns:
            return
        conn.execute(text("ALTER TABLE users ADD COLUMN email VARCHAR(255)"))
        conn.execute(text("ALTER TABLE users ADD COLUMN password_hash VARCHAR(255)"))
        # Múltiplos NULL são permitidos em unique index (Postgres) — o seed
        # id 1 nasce sem email até o CLI vinculá-lo (AUTH-25)
        conn.execute(text("CREATE UNIQUE INDEX uq_users_email ON users (email)"))


def _migrate_activities_shoe_id() -> None:
    """Migração idempotente da coluna ``shoe_id`` em ``activities`` (feature tenis).

    Condicional à coluna: base nova (create_all já criou a FK e o índice)
    não tenta recriar. Executa em transação própria para isolar falhas.
    """
    with engine.begin() as conn:
        columns = {
            row[0]
            for row in conn.execute(
                text(
                    "SELECT column_name FROM information_schema.columns "
                    "WHERE table_name = 'activities'"
                )
            )
        }
        if "shoe_id" in columns:
            return
        conn.execute(
            text(
                "ALTER TABLE activities ADD COLUMN shoe_id INTEGER "
                "REFERENCES shoes(id) ON DELETE SET NULL"
            )
        )
        conn.execute(text("CREATE INDEX ix_activities_shoe_id ON activities (shoe_id)"))


def _migrate_vdot_zone_configs() -> None:
    """Migração idempotente da tabela ``vdot_zone_configs`` (feature pace-zones).

    Cria a tabela e o índice se não existirem. Executa em transação própria
    para isolar falhas. O seed dos dados é feito em init_db() após create_all.
    """
    with engine.begin() as conn:
        tables = {
            row[0]
            for row in conn.execute(
                text(
                    "SELECT table_name FROM information_schema.tables "
                    "WHERE table_schema = 'public' AND table_name = 'vdot_zone_configs'"
                )
            )
        }
        if "vdot_zone_configs" in tables:
            return
        conn.execute(text("""
            CREATE TABLE vdot_zone_configs (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                vdot DOUBLE PRECISION NOT NULL,
                source VARCHAR(60) NOT NULL,
                test_date DATE NOT NULL,
                distance_m DOUBLE PRECISION NOT NULL,
                time_s DOUBLE PRECISION NOT NULL,
                zones JSONB NOT NULL,
                equivalencias JSONB NOT NULL,
                valid_from DATE NOT NULL,
                created_at TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'utc')
            )
        """))
        conn.execute(text("CREATE INDEX ix_vdotzoneconfigs_user_valid_from ON vdot_zone_configs (user_id, valid_from)"))


def _migrate_schema() -> None:
    """Executa todas as migrações idempotentes de schema, cada uma em seu
    bloco independente. Ordem: users (auth) → activities (tenis) → vdot zones (pace-zones)."""
    _migrate_users_columns()
    _migrate_activities_shoe_id()
    _migrate_vdot_zone_configs()


def init_db() -> None:
    """Cria as tabelas, migra esquemas antigos e semeia o usuário default."""
    from app.db import models  # noqa: F401 — registra os modelos no Base
    from app.db.models import DEFAULT_USER_ID, HrZoneConfig, Race, User, VdotZoneConfig

    Base.metadata.create_all(bind=engine)
    _migrate_schema()

    with SessionLocal() as db:
        if db.get(User, DEFAULT_USER_ID) is None:
            db.add(User(id=DEFAULT_USER_ID, display_name="Leonardo"))
            db.commit()

        # HOME-22/23: a meia do countdown é fato real, não métrica
        # (decisão do spec) — semeada só quando o usuário 1 não tem
        # prova nenhuma. Guard por usuário, padrão AD-019 do seed
        # acima: re-executar não duplica, prova de outro usuário não
        # bloqueia. Sem setval — id auto como nos demais seeds de dado.
        if (
            db.query(Race)
            .filter(Race.user_id == DEFAULT_USER_ID)
            .first()
            is None
        ):
            db.add(
                Race(
                    user_id=DEFAULT_USER_ID,
                    name="The Best Açaí",
                    date=date(2026, 11, 8),
                    distance_m=21097.5,
                    goal_time_s=None,
                )
            )
            db.commit()

        # HRZ-07: o usuário 1 nasce com a config de zonas (lthr +
        # defaults, valid_from hoje) — NENHUMA métrica é seedada: vêm do
        # sync (HRZ-05) ou da edição manual; métrica manual seedada
        # bloquearia o auto-update para sempre (manual-wins). Guarda de
        # existência (padrão AD-019): re-executar não duplica.
        if (
            db.query(HrZoneConfig)
            .filter(HrZoneConfig.user_id == DEFAULT_USER_ID)
            .first()
            is None
        ):
            db.add(
                HrZoneConfig(
                    user_id=DEFAULT_USER_ID,
                    method="lthr",
                    bounds={"zones": DEFAULT_BOUNDS["lthr"]},
                    valid_from=date.today(),
                )
            )
            db.commit()

        # PZ-02: seed VDOT zones from vdot_zones.json for user 1 — idempotent guard
        # (padrão AD-019): re-executar não duplica.
        if (
            db.query(VdotZoneConfig)
            .filter(VdotZoneConfig.user_id == DEFAULT_USER_ID)
            .first()
            is None
        ):
            zones_path = settings.vdot_zones_path
            try:
                with open(zones_path, encoding="utf-8") as file:
                    data = json.load(file)
            except (OSError, json.JSONDecodeError):
                pass  # arquivo ausente/inválido → seed não feito; endpoint virará 500
            else:
                db.add(
                    VdotZoneConfig(
                        user_id=DEFAULT_USER_ID,
                        vdot=float(data["vdot"]),
                        source=data["source"],
                        test_date=date.fromisoformat(data["test_date"]),
                        distance_m=float(data["distancia_metros"]),
                        time_s=float(data["tempo_segundos"]),
                        zones=data["zones"],
                        equivalencias=data["equivalencias"],
                        valid_from=date.fromisoformat(data["test_date"]),
                    )
                )
                db.commit()

        # AUTH-27: o seed com id explícito não avança a sequência — sem o
        # setval, o primeiro INSERT sem id (register/CLI) colide com a
        # pkey 1. Pendência do handoff, corrigida aqui para acompanhar o
        # seed. Idempotente: reajusta para MAX(id) (COALESCE cobre tabela
        # vazia). Postgres-only — único dialeto (AD-007).
        db.execute(
            text("SELECT setval('users_id_seq', (SELECT COALESCE(MAX(id), 1) FROM users))")
        )
