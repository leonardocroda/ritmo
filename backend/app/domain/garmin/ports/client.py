"""Ports para o domínio Garmin."""

from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol, runtime_checkable

from app.domain.garmin.domain.entities import GarminActivity, GarminSleep, GarminHRV, SyncStatus


@runtime_checkable
class GarminClient(Protocol):
    async def fetch_activities(self, after: datetime) -> Sequence[GarminActivity]: ...
    async def fetch_splits(self, activity_id: int) -> Sequence[dict]: ...
    async def fetch_sleep(self, start: date, end: date) -> Sequence[GarminSleep]: ...
    async def fetch_hrv(self, start: date, end: date) -> Sequence[GarminHRV]: ...
    async def fetch_rhr(self, start: date, end: date) -> Sequence[dict]: ...
    async def fetch_stress(self, start: date, end: date) -> Sequence[dict]: ...


@runtime_checkable
class TokenStore(Protocol):
    def get_tokens(self, user_id: int) -> dict | None: ...
    def save_tokens(self, user_id: int, tokens: dict) -> None: ...
    def delete_tokens(self, user_id: int) -> None: ...